/**
 * Cleanup transformer for business.adobe.com.
 * Removes non-authorable chrome and widget UI. Selectors come from
 * migration-work/cleaned.html.
 */

function isEmptySection(el) {
  if (!el) return false;
  if (el.querySelector('img, picture, video, iframe, table, hr')) return false;
  return el.textContent.trim() === '';
}

export default function transform(hookName, element, payload) {
  const doc = element.ownerDocument || document;

  if (hookName === 'beforeTransform') {
    // Global chrome
    WebImporter.DOMUtils.remove(element, [
      'header.global-navigation',
      'div.feds-topnav-wrapper',
      'footer.global-footer',
      'div.feds-footer-icons',
      'div.notification-visibility-hidden',
      '#page-load-ok-milo',
      'script',
      'style',
      'noscript',
      'link',
      'iframe',
    ]);

    // Non-content body-level div (body > div:nth-of-type(3) on source)
    const body = doc.body;
    if (body) {
      const strayDiv = body.querySelector(':scope > div:nth-of-type(3)');
      if (strayDiv && !strayDiv.querySelector('main')) strayDiv.remove();
    }

    // Card metadata section (CaaS metadata, not authorable page content)
    element.querySelectorAll('div.card-metadata').forEach((cm) => {
      const section = cm.closest('div.section');
      cm.remove();
      if (section && isEmptySection(section)) section.remove();
    });

    // Source (Milo) section-metadata divs, including those nested inside
    // fragments (e.g. "m-spacing-top" in the customer-brands fragment).
    // Section Metadata is regenerated by the sections transformer.
    WebImporter.DOMUtils.remove(element, ['div.section-metadata']);

    // Logo scroller navigation buttons/gradients
    WebImporter.DOMUtils.remove(element, ['div.nav-grad', 'button.nav-button']);

    // Brand Concierge interactive input UI (keep header text, prompt chips, legal)
    WebImporter.DOMUtils.remove(element, [
      'div.brand-concierge section.bc-input-field',
      'div.brand-concierge textarea',
      'div.brand-concierge input',
      '#bc-label-tooltip',
    ]);

    // Empty spacer sections at main level (e.g. main > div.section:nth-of-type(9))
    element.querySelectorAll('main > div.section').forEach((section) => {
      if (isEmptySection(section)) section.remove();
    });
  }

  if (hookName === 'afterTransform') {
    // Unwrap any remaining buttons (e.g. prompt chips) keeping their content
    element.querySelectorAll('button').forEach((btn) => {
      const parent = btn.parentNode;
      if (!parent) return;
      while (btn.firstChild) parent.insertBefore(btn.firstChild, btn);
      btn.remove();
    });

    WebImporter.DOMUtils.remove(element, [
      'textarea',
      'input',
      'form',
      'script',
      'style',
      'noscript',
      'link',
      'iframe',
    ]);

    // Strip tracking attributes
    element.querySelectorAll('*').forEach((el) => {
      [...el.attributes].forEach((attr) => {
        const n = attr.name;
        // keep data-excat-* markers used by the sections transformer
        if (n.startsWith('data-excat-')) return;
        if (n.startsWith('daa-') || n.startsWith('data-') || n === 'onclick') {
          el.removeAttribute(n);
        }
      });
    });
  }
}
